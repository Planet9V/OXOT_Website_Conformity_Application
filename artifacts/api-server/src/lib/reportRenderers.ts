const MATRIX_STATUSES = ["not_met", "partial", "in_progress", "not_started"] as const;
const MATRIX_RISKS = ["critical", "high", "medium", "low"] as const;

export function renderRiskAnalysis(s: AssessmentSnapshot, figures: Figures): string {
  const cells: number[][] = MATRIX_RISKS.map((risk) =>
    MATRIX_STATUSES.map(
      (status) => s.gaps.filter((g) => (g.riskRating ?? "medium") === risk && g.status === status).length,
    ),
  );
  const matrix = riskMatrix({
    rows: cells,
    rowLabels: ["Critical", "High", "Medium", "Low"],
    colLabels: ["Not met", "Partially met", "In progress", "Not started"],
  });
  const register = s.gaps
    .slice(0, 14)
    .map(
      (g) =>
        `<tr><td>${esc(g.refCode)}</td><td>${esc(g.title)}</td><td>${riskBadge(g.riskRating)}</td><td>${badge(g.status)}</td><td>${esc(g.owner || "—")}</td><td>${dateFmt(g.dueDate)}</td></tr>`,
    )
    .join("");
  return `<figure>${matrix}${figures.caption("Open requirement exposure: recorded risk rating × evaluation status (counts).")}</figure>
<table>
<tr><th>Ref</th><th>Requirement</th><th>Risk</th><th>Status</th><th>Owner</th><th>Due</th></tr>
${register || '<tr><td colspan="6" class="muted">No open requirements — the risk register is clear.</td></tr>'}
</table>`;
}

export function renderStandardsSection(s: AssessmentSnapshot, reg: CitationRegistry): string {
  const cra = reg.cite("reg:" + s.assessment.regulationKey) || reg.cite("bib:cra");
  const enisa = reg.cite("bib:enisa-standards");
  const rows = s.appliedStandards
    .map((std) => {
      const cite = reg.cite(`std:${std.reference}`);
      return `<tr><td><strong>${esc(std.reference)}</strong> ${cite}</td><td>${esc(std.title ?? "—")}</td><td>${std.coverage === "full" ? '<span class="badge ok">Applied in full</span>' : '<span class="badge warn">Applied in part</span>'}</td><td>${esc(std.notes ?? "")}</td></tr>`;
    })
    .join("");
  const intro = rows
    ? `<p>The manufacturer records the following harmonised standards and technical specifications as applied to the product. Where a harmonised standard whose reference has been published in the Official Journal is applied <em>in full</em>, conformity with the essential requirements it covers is presumed ${cra}; partial application confers no presumption and the corresponding requirements must be evidenced directly ${enisa}.</p>
<table><tr><th>Reference</th><th>Title</th><th>Coverage</th><th>Notes</th></tr>${rows}</table>`
    : `<p>No harmonised standards or technical specifications have been recorded against this assessment. Conformity with each essential requirement must therefore be demonstrated directly through the technical documentation, without presumption of conformity ${cra}.</p>`;
  const advisory = s.standardsAdvisory
    ? `<div class="callout"><strong>Route validity advisory.</strong> ${esc(s.standardsAdvisory)}</div>`
    : "";
  return intro + advisory;
}

export function renderIncidents(s: AssessmentSnapshot, options: ReportOptions, figures: Figures): string {
  if (s.incidents.length === 0) {
    return `<p>No reportable incidents or actively exploited vulnerabilities are recorded against this product. The Article 14 reporting apparatus (24-hour early warning, 72-hour notification, final report) is nonetheless a live obligation from the moment of awareness; readiness is assessed under the remediation programme.</p>`;
  }
  const rows = s.incidents
    .map((i) => {
      const clockCell = (idx: number): string => {
        const c = i.clocks[idx];
        if (!c) return "<td>—</td>";
        if (c.doneAt) return `<td><span class="badge ok">Done ${dateFmt(c.doneAt)}</span></td>`;
        return `<td><span class="badge ${c.overdue ? "bad" : "warn"}">${c.overdue ? "Overdue" : "Due"} ${dateFmt(c.dueAt)}</span></td>`;
      };
      return `<tr><td>${esc(i.title)}</td><td>${esc(i.kind === "exploited_vulnerability" ? "Exploited vulnerability (Art 14(1))" : "Severe incident (Art 14(3))")}</td><td>${riskBadge(i.severity)}</td><td>${dateFmt(i.detectedAt)}</td>${clockCell(0)}${clockCell(1)}${clockCell(2)}<td>${badge(isIncidentClosed(i.status) ? "met" : "in_progress")}</td></tr>`;
    })
    .join("");
  const timelineItems: TimelineItem[] = s.deadlines
    .filter((d) => d.kind === "statutory")
    .slice(0, 6)
    .map((d) => ({ label: d.label.length > 34 ? d.label.slice(0, 33) + "…" : d.label, date: new Date(d.dueAt), kind: d.done ? "done" : "due" }));
  const timeline =
    timelineItems.length > 0
      ? `<figure>${timelineChart({
          items: timelineItems,
          start: new Date(new Date(s.generatedAt).getTime() - 14 * 86_400_000),
          end: new Date(new Date(s.generatedAt).getTime() + 45 * 86_400_000),
        })}${figures.caption("Article 14 reporting clocks around the snapshot date.")}</figure>`
      : "";
  const detail = options.includeIncidentDetail
    ? s.incidents
        .map(
          (i) => `<h3>${esc(i.title)}</h3>
<table>
<tr><td style="width:34%" class="muted">Member states affected</td><td>${esc(i.memberStates || "Not yet recorded")}</td></tr>
<tr><td class="muted">Corrective / mitigating measures</td><td>${esc(i.correctiveMeasures || "Not yet recorded")}</td></tr>
<tr><td class="muted">Mitigations available to users</td><td>${esc(i.userMitigations || "Not yet recorded")}</td></tr>
</table>`,
        )
        .join("")
    : "";
  return `<table>
<tr><th>Incident</th><th>Track</th><th>Severity</th><th>Detected</th><th>Early warning (24h)</th><th>Notification (72h)</th><th>Final report</th><th>Status</th></tr>
${rows}
</table>${timeline}${detail}`;
}

export function renderSupplyChain(s: AssessmentSnapshot, reg: CitationRegistry, figures: Figures): string {
  if (s.boms.length === 0) {
    return `<p>No bill of materials has been ingested for this product. Component-level transparency (SBOM) is required by Annex I Part II ${reg.cite("reg:" + s.assessment.regulationKey) || reg.cite("bib:cra")}; producing and maintaining one is tracked in the remediation programme.</p>`;
  }
  const rows = s.boms
    .map(
      (b) =>
        `<tr><td>${esc(b.name)}</td><td>${esc(b.bomType.toUpperCase())}</td><td>${b.componentCount}</td><td>${b.findingCount}</td></tr>`,
    )
    .join("");
  const sev = s.boms.reduce(
    (acc, b) => ({
      critical: acc.critical + b.findingsBySeverity.critical,
      high: acc.high + b.findingsBySeverity.high,
      medium: acc.medium + b.findingsBySeverity.medium,
      low: acc.low + b.findingsBySeverity.low,
      other: acc.other + b.findingsBySeverity.other,
    }),
    { critical: 0, high: 0, medium: 0, low: 0, other: 0 },
  );
  const chart = barChart({
    bars: [
      { label: "Critical", value: sev.critical, max: Math.max(1, sev.critical, sev.high, sev.medium, sev.low), color: CHART_BAD },
      { label: "High", value: sev.high, max: Math.max(1, sev.critical, sev.high, sev.medium, sev.low), color: CHART_WARN },
      { label: "Medium", value: sev.medium, max: Math.max(1, sev.critical, sev.high, sev.medium, sev.low), color: CHART_ACCENT },
      { label: "Low / info", value: sev.low + sev.other, max: Math.max(1, sev.critical, sev.high, sev.medium, sev.low + sev.other), color: CHART_MUTED },
    ],
    width: 460,
  });
  const gaps =
    s.upstreamNotificationGaps > 0
      ? `<div class="callout"><strong>${s.upstreamNotificationGaps} upstream maintainer notification(s) pending.</strong> Article 13(6) requires the manufacturer to report identified vulnerabilities in integrated components to their maintainers; the pending items are listed in the workbench BOM register.</div>`
      : "";
  return `<table><tr><th>Bill of materials</th><th>Type</th><th>Components</th><th>Findings</th></tr>${rows}</table>
<figure>${chart}${figures.caption("Open component findings by severity across all ingested BOMs.")}</figure>${gaps}`;
}

