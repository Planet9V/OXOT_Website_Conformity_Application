export function renderMethodology(s: AssessmentSnapshot, reg: CitationRegistry): string {
  const cra = reg.cite("reg:" + s.assessment.regulationKey) || reg.cite("bib:cra");
  const blue = reg.cite("bib:blue-guide");
  const enisa = reg.cite("bib:enisa-standards");
  const nlf = reg.cite("bib:768-2008");
  return `<p>This report is compiled from the OXOT Conformity Workbench's working record for assessment CONF-${s.assessment.id}. The assessment method proceeds in five stages: scoping against the regulation's definition of a product with digital elements ${cra}; classification against the importance criteria of Annex III and selection of a conformity assessment route consistent with the New Legislative Framework ${nlf}${blue}; obligation mapping, in which the essential requirements of Annex I Parts I and II are decomposed into discrete, evaluable requirements; evaluation, in which each requirement is assessed as met, partially met, not met, not applicable, or not yet started, with an implementation note, an accountable owner, a risk rating and a due date; and documentation review across the technical file artefacts required for the chosen route.</p>
<p>Quantitative figures use the workbench grading model: the overall score weights requirement coverage at 70% and documentation completeness at 30%; a requirement evaluated as <em>not met</em> with a critical or high risk rating is a <em>blocker</em> irrespective of the aggregate score. Theme coverage scores are the grading model's per-theme results on a 0–100 scale. These conventions are held constant across reports, so scores are comparable over time and across products.</p>
<p>Evidence is registered with content hashes (SHA-256) and timestamps in an append-only activity ledger, providing a chain of custody from claim to artefact. Where harmonised standards are recorded as applied in full, the corresponding requirements benefit from a presumption of conformity ${cra}; the mapping between standards and requirements follows the published standardisation mapping ${enisa}.</p>
<p><strong>Limitations.</strong> Evaluations and evidence are self-declared by the manufacturer's assessment team and reviewed by OXOT; this report is a conformity-readiness analysis, not a notified-body certificate or a legal opinion. Figures reflect the data snapshot of ${dateFmt(s.generatedAt)} and do not incorporate later changes to the working record.</p>`;
}

export function renderRequirementMatrix(s: AssessmentSnapshot, includeNotes: boolean): string {
  const byTheme = new Map<string, SnapshotRequirement[]>();
  for (const r of s.requirements) {
    const list = byTheme.get(r.themeName) ?? [];
    list.push(r);
    byTheme.set(r.themeName, list);
  }
  const blocks: string[] = [];
  for (const [themeName, reqs] of byTheme) {
    const rows = reqs
      .map(
        (r) =>
          `<tr><td style="white-space:nowrap">${esc(r.refCode)}</td><td>${esc(r.title)}</td><td>${badge(r.status)}</td><td>${riskBadge(r.riskRating)}</td><td>${esc(r.owner || "—")}</td><td>${dateFmt(r.dueDate)}</td>${includeNotes ? `<td>${esc(r.note || "")}</td>` : ""}</tr>`,
      )
      .join("");
    blocks.push(`<h3>${esc(themeName)}</h3>
<table><tr><th>Ref</th><th>Requirement</th><th>Status</th><th>Risk</th><th>Owner</th><th>Due</th>${includeNotes ? "<th>Implementation note</th>" : ""}</tr>${rows}</table>`);
  }
  return blocks.join("");
}

