export function renderKpiBand(s: AssessmentSnapshot): string {
  const nearest = s.deadlines.filter((d) => !d.done);
  const nearestText = nearest.length
    ? `${daysUntil(nearest[0]!.dueAt, s.generatedAt)}d`
    : "—";
  const nearestLabel = nearest.length ? nearest[0]!.label : "No statutory deadline pending";
  const openIncidentCount = s.incidents.filter((i) => !isIncidentClosed(i.status)).length;

  const kpis: { val: string; label: string; sub: string; tone?: string }[] = [
    {
      val: s.grade.overallGrade,
      label: "Overall Grade",
      sub: `Score: ${s.grade.overallScore}/100`,
      tone: s.grade.overallGrade === "A" || s.grade.overallGrade === "B" ? "ok" : "bad",
    },
    {
      val: `${s.grade.overallScore}`,
      label: "Compliance Score",
      sub: "Out of 100 max",
      tone: s.grade.overallScore >= 80 ? "ok" : s.grade.overallScore >= 60 ? "warn" : "bad",
    },
    {
      val: `${s.readiness.percent}%`,
      label: "Requirements Met",
      sub: `${s.readiness.met} of ${s.readiness.total - s.readiness.notApplicable} applicable`,
      tone: s.readiness.percent >= 80 ? "ok" : "warn",
    },
    {
      val: `${s.grade.blockerCount}`,
      label: "Critical Blockers",
      sub: "Action items capping grade",
      tone: s.grade.blockerCount > 0 ? "bad" : "ok",
    },
    {
      val: `${openIncidentCount}`,
      label: "Open Incidents",
      sub: "Article 14 CSIRT tracks",
      tone: openIncidentCount > 0 ? "warn" : "ok",
    },
    {
      val: nearestText,
      label: "Nearest SLA Clock",
      sub: nearestLabel,
      tone: nearestText.includes("d") ? "warn" : "muted",
    },
  ];

  return `<div class="kpi-grid">${kpis
    .map(
      (k) =>
        `<div class="kpi-card ${k.tone ? `kpi-${k.tone}` : ""}"><div class="kpi-label">${esc(k.label)}</div><div class="kpi-val">${esc(k.val)}</div><div class="kpi-sub">${esc(k.sub)}</div></div>`,
    )
    .join("")}</div>`;
}

export function renderPostureCharts(s: AssessmentSnapshot, figures: Figures): string {
  const donut = donutChart({
    segments: [
      { label: "Met", value: s.readiness.met, color: CHART_OK },
      { label: "Partially met", value: s.readiness.partial, color: CHART_WARN },
      { label: "Open", value: s.readiness.open, color: CHART_BAD },
      { label: "Not applicable", value: s.readiness.notApplicable, color: CHART_GRID },
    ],
    centerLabel: `${s.readiness.percent}%`,
    centerSub: "requirements met",
  });
  const bars = barChart({
    bars: s.themes
      .filter((t) => t.total > 0)
      .map((t) => ({
        label: t.name,
        value: t.score,
        max: 100,
        color: t.score >= 80 ? CHART_OK : t.score >= 50 ? CHART_WARN : CHART_BAD,
      })),
    valueSuffix: "%",
  });
  return `<div class="figure-row">
<figure>${donut}${figures.caption("Evaluation status across all applicable essential requirements.")}</figure>
<figure>${bars}${figures.caption("Coverage score by obligation theme (grading model, 0–100).")}</figure>
</div>`;
}

export function renderClassificationRoute(s: AssessmentSnapshot, reg: CitationRegistry): string {
  const cra = reg.cite("reg:" + s.assessment.regulationKey) || reg.cite("bib:cra");
  const scopeLine =
    s.assessment.scopeResult === "out_of_scope"
      ? `<p>The scoping review concluded that the product is <strong>outside the scope</strong> of the regulation ${cra}; the remainder of this report records the analysis supporting that conclusion.</p>`
      : `<p>The scoping review concluded that the product is <strong>within scope</strong> of the regulation as a product with digital elements ${cra}.</p>`;
  const cls = s.assessment.className
    ? `<p>The product is classified as <strong>${esc(s.assessment.className)}</strong>. The selected conformity assessment route is <strong>${esc(s.assessment.routeName ?? s.assessment.routeKey ?? "not yet selected")}</strong>. The classification and route recorded here are those the eventual EU declaration of conformity would assert.</p>`
    : `<p>Classification has not yet been recorded; route selection and the resulting obligations remain provisional.</p>`;
  const advisory = s.standardsAdvisory
    ? `<div class="callout"><strong>Route validity advisory.</strong> ${esc(s.standardsAdvisory)}</div>`
    : "";
  return scopeLine + cls + advisory;
}

