/**
 * Deterministic section renderers. Pure functions from a frozen snapshot to
 * HTML strings — no I/O, no randomness, so a report's deterministic sections
 * are reproducible byte-for-byte from its stored snapshot.
 */

export const esc = escapeXml; // HTML-safe for our subset (no attribute quirks used)

export class Figures {
  private n = 0;
  caption(text: string): string {
    this.n += 1;
    return `<figcaption>Figure ${this.n}. ${esc(text)}</figcaption>`;
  }
}

function badge(status: string): string {
  const cls =
    status === "met" ? "ok" : status === "partial" || status === "in_progress" ? "warn" : status === "not_met" ? "bad" : "na";
  return `<span class="badge ${cls}">${esc(STATUS_LABELS[status] ?? status)}</span>`;
}

function riskBadge(risk: string | null): string {
  if (!risk) return '<span class="muted">—</span>';
  const cls = risk === "critical" || risk === "high" ? "bad" : risk === "medium" ? "warn" : "na";
  return `<span class="badge ${cls}">${esc(risk)}</span>`;
}

const dateFmt = (iso: string | null | undefined): string => (iso ? iso.slice(0, 10) : "—");

function daysUntil(iso: string, from: string): number {
  return Math.ceil((new Date(iso).getTime() - new Date(from).getTime()) / 86_400_000);
}

